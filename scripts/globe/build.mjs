// Generates the analytics globe's data (web/src/features/analytics/globe/):
// land.ts, the land as rows of dots every 1.5 degrees, and centres.ts, a
// point inside each country by ISO code. Both come from Natural Earth via
// world-atlas (public domain); ISO numeric codes map to alpha-2 with
// i18n-iso-countries' codes.json (MIT). Run once, commit the output:
//
//   cd "$(mktemp -d)" && npm pack world-atlas@2 i18n-iso-countries@7 &&
//     for f in *.tgz; do mkdir "${f%.tgz}" && tar xzf "$f" -C "${f%.tgz}"; done
//   node scripts/globe/build.mjs <that dir>/world-atlas-*/package \
//     <that dir>/i18n-iso-countries-*/package/codes.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [atlas, codesFile] = process.argv.slice(2);
if (!atlas || !codesFile) {
  console.error("usage: node scripts/globe/build.mjs <world-atlas dir> <codes.json>");
  process.exit(2);
}
const out = join(dirname(fileURLToPath(import.meta.url)), "../../web/src/features/analytics/globe");
const STEP = 1.5;

/** A TopoJSON file's polygons as rings of [lon, lat], per geometry. */
function polygons(file, object) {
  const topo = JSON.parse(readFileSync(join(atlas, file), "utf8"));
  const { scale, translate } = topo.transform;
  const arcs = topo.arcs.map((a) => {
    let x = 0;
    let y = 0;
    return a.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
    });
  });
  const ring = (ids) =>
    ids.flatMap((i, k) => {
      const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
      return k ? a.slice(1) : a;
    });
  return topo.objects[object].geometries.map((g) => ({
    id: g.id,
    name: g.properties?.name,
    polys: (g.type === "Polygon" ? [g.arcs] : g.type === "MultiPolygon" ? g.arcs : []).map(
      (p) => p.map(ring),
    ),
  }));
}

// Land: each row of latitude has dots in proportion to its length, so
// they sit evenly on the sphere. A row is run lengths, water first, in
// base 36 joined by ".".
const rings = polygons("land-110m.json", "land").flatMap((g) => g.polys.flat());
const inside = (x, y) => {
  let c = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  }
  return c;
};
const rows = [];
let dots = 0;
for (let lat = 90 - STEP / 2; lat > -90; lat -= STEP) {
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  const runs = [];
  let cur = false;
  let len = 0;
  for (let k = 0; k < n; k++) {
    const v = inside(-180 + (k + 0.5) * (360 / n), lat);
    if (v) dots++;
    if (v === cur) len++;
    else {
      runs.push(len);
      cur = v;
      len = 1;
    }
  }
  runs.push(len);
  rows.push(runs.map((r) => r.toString(36)).join("."));
}
writeFileSync(
  join(out, "land.ts"),
  `// Generated by scripts/globe/build.mjs from Natural Earth (public domain); do not edit.

/** The land as dots: rows of latitude from the north, run lengths of water and land. */
export const land = {
  step: ${STEP},
  dots: ${dots},
  rows: "${rows.join(",")}",
} as const;
`,
);

// Centres: the area-weighted centre of each country's largest polygon
// (its mainland), areas measured with longitude shrunk by latitude.
const alpha2 = new Map(JSON.parse(readFileSync(codesFile, "utf8")).map(([a2, , num]) => [num, a2]));
const named = { Kosovo: "XK" };
const centres = {};
// Some territories share their country's code (Ashmore and Cartier
// Islands are AU's 036): the largest polygon of any of them wins.
const areas = {};
for (const c of polygons("countries-50m.json", "countries")) {
  const code = alpha2.get(c.id) ?? named[c.name];
  if (!code) continue;
  let best = null;
  for (const [ring] of c.polys) {
    // A ring cut at the antimeridian (Russia's, Fiji's) continues east of
    // 180 instead of jumping back to -180.
    const xs = ring.map((p) => p[0]);
    const wraps = Math.max(...xs) - Math.min(...xs) > 180;
    const outer = wraps ? ring.map(([x, y]) => [x < 0 ? x + 360 : x, y]) : ring;
    const mid = outer.reduce((s, p) => s + p[1], 0) / outer.length;
    const k = Math.cos((mid * Math.PI) / 180);
    let a = 0;
    let cx = 0;
    let cy = 0;
    for (let i = 0, j = outer.length - 1; i < outer.length; j = i++) {
      const [x0, y0] = [outer[j][0] * k, outer[j][1]];
      const [x1, y1] = [outer[i][0] * k, outer[i][1]];
      const f = x0 * y1 - x1 * y0;
      a += f;
      cx += (x0 + x1) * f;
      cy += (y0 + y1) * f;
    }
    if (a === 0) continue;
    if (!best || Math.abs(a) > Math.abs(best.a)) {
      best = { a, x: cx / (3 * a) / k, y: cy / (3 * a) };
    }
  }
  if (!best || Math.abs(best.a) <= (areas[code] ?? 0)) continue;
  areas[code] = Math.abs(best.a);
  const lon = best.x > 180 ? best.x - 360 : best.x;
  centres[code] = [Math.round(best.y * 10) / 10, Math.round(lon * 10) / 10];
}
const sorted = Object.keys(centres).sort();
writeFileSync(
  join(out, "centres.ts"),
  `// Generated by scripts/globe/build.mjs from Natural Earth (public domain); do not edit.

/** A point inside each country's mainland, [latitude, longitude], by ISO code. */
export const centres: Readonly<Record<string, readonly [number, number]>> = {
${sorted.map((k) => `  ${k}: [${centres[k][0]}, ${centres[k][1]}],`).join("\n")}
};
`,
);
console.error(`land: ${rows.length} rows, ${dots} dots; centres: ${sorted.length} countries`);
