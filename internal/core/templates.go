// postgresTemplate is a Postgres template running image, which keeps the
// official image's entrypoint and variables.
func postgresTemplate(name apitypes.Template, title, description, image string) dbTemplate {
	return dbTemplate{
		name: name, title: title, license: "PostgreSQL", description: description, image: image,
		port:      defaultPostgresPort,
		health:    node.HealthPostgres,
		mountPath: "/var/lib/postgresql/data",
		memoryMB:  512,
		// queryStatsFlags: pg_stat_statements for the Data panel's Health
		// tab (ADR 0069); Dock creates the extension once the release is
		// active (afterActive).
		cmd: "exec docker-entrypoint.sh postgres -c shared_buffers=128MB -c effective_cache_size=384MB" +
			" -c work_mem=4MB -c maintenance_work_mem=64MB -c max_connections=50 -c random_page_cost=1.1 " + queryStatsFlags,
		database: apitypes.DatabasePostgres,
		backup:   apitypes.BackupPostgres,
		vars: func(svc, password string) map[string]string {
			return map[string]string{
				"POSTGRES_USER":     "postgres",
				"POSTGRES_PASSWORD": password,
				"POSTGRES_DB":       "app",
				"DATABASE_URL": fmt.Sprintf("postgresql://${{%[1]s.POSTGRES_USER}}:${{%[1]s.POSTGRES_PASSWORD}}@%[1]s:%[2]d/${{%[1]s.POSTGRES_DB}}",
					svc, defaultPostgresPort),
			}
		},
		exports: []string{"DATABASE_URL"},
	}
}

// redisTemplate is a Redis-compatible template: server is the image's
// server binary.
func redisTemplate(name apitypes.Template, title, license, description, image, server string) dbTemplate {
	return dbTemplate{
		name: name, title: title, license: license, description: description, image: image,
		port:      6379,
		mountPath: "/data",
		memoryMB:  256,
		// noeviction: Redis is often a queue, where silently dropping keys
		// is worse than an error.
		cmd: `exec docker-entrypoint.sh ` + server + ` --requirepass "$REDIS_PASSWORD" --appendonly yes` +
			" --maxmemory 200mb --maxmemory-policy noeviction",
		backup:   apitypes.BackupRedis,
		database: apitypes.DatabaseRedis,
		vars: func(svc, password string) map[string]string {
			return map[string]string{
				"REDIS_PASSWORD": password,
				"REDIS_URL":      fmt.Sprintf("redis://default:${{%s.REDIS_PASSWORD}}@%s:6379", svc, svc),
			}
		},
		exports: []string{"REDIS_URL"},
	}
}

// mysqlTemplate is a MySQL or MariaDB template: server is the image's
// server binary, prefix its variables' (MYSQL_ or MARIADB_). Apps connect
// as root to the app database; backups dump every database but the
// server's own with mysqldump or mariadb-dump.
func mysqlTemplate(name apitypes.Template, title, license, description, image, server, prefix string, memoryMB int) dbTemplate {
	return dbTemplate{
		name: name, title: title, license: license, description: description, image: image,
		port:      3306,
		mountPath: "/var/lib/mysql",
		memoryMB:  memoryMB,
		cmd:       "exec docker-entrypoint.sh " + server + " --innodb-buffer-pool-size=128M --max-connections=50",
		database:  apitypes.DatabaseMySQL,
		backup:    apitypes.BackupMySQL,
		vars: func(svc, password string) map[string]string {
			return map[string]string{
				prefix + "_ROOT_PASSWORD": password,
				prefix + "_DATABASE":      "app",
				"DATABASE_URL": fmt.Sprintf("mysql://root:${{%[1]s.%[2]s_ROOT_PASSWORD}}@%[1]s:3306/${{%[1]s.%[2]s_DATABASE}}",
					svc, prefix),
			}
		},
		exports: []string{"DATABASE_URL"},
	}
}

// templateOf returns a service's template, if it has one.
func templateOf(s store.Service) (dbTemplate, bool) {
	t, ok := templates[apitypes.Template(s.Template)]
	return t, ok
}

// ListTemplates lists the database templates.
func (c *Core) ListTemplates(context.Context, Actor) []apitypes.TemplateInfo {
	out := make([]apitypes.TemplateInfo, 0, len(templates))
	for _, name := range slices.Sorted(maps.Keys(templates)) {
		t := templates[name]
		out = append(out, apitypes.TemplateInfo{
			Name: t.name, Description: t.description, Image: t.image, MemoryMB: t.memoryMB,
			MountPath: t.mountPath, Exports: t.exports,
		})
	}
	return out
}

// newPassword returns a generated password: 32 random base32 characters
// (160 bits), safe in URLs and shells without escaping.
func newPassword() string { return rand.Text() + rand.Text()[:6] }

// templateOptions say what createFromTemplate does after creating.
type templateOptions struct {
	// noDeploy leaves the first deploy to the caller (a Redis restore
	// fills the volume first).
	noDeploy bool
	// done is called when the first release finished (ok: it is active).
	done func(ok bool)
	// image replaces the template's image (a snapshot restore runs the
	// image its data files were written by).
	image string
	// keep are values for variables the template generates, used instead
	// (a snapshot restore keeps the credentials in its data files).
	keep map[string]string
	// marksFrom is the service whose sensitive columns and key patterns
	// the new one takes (a restore copies a database, so masking must hold
	// on the copy).
	marksFrom int64
}

// createFromTemplate creates a service from a template: the service with
// the template's settings (its image at the newest digest the daily check
// saw, templateImage), its volume and generated variables staged, and
// (unless opts.noDeploy) an image deploy that applies them. A deploy that
// can't start (server offline) is an error, but the service exists and
// deploys like any other once the cause is fixed.
func (c *Core) createFromTemplate(ctx context.Context, a Actor, es envScope, name string, t dbTemplate, opts templateOptions) (svcScope, error) {
	var ss svcScope
	image := opts.image
	if image == "" {
		image = c.templateImage(ctx, c.store.Queries, t)
	}
	err := c.store.Tx(ctx, func(q *store.Queries) error {
		s, err := q.CreateService(ctx, store.CreateServiceParams{
			EnvironmentID: es.env.ID, Name: name, Image: image, StartCommand: t.cmd, MemoryMb: int64(t.memoryMB),
		})
		if store.IsUnique(err) {
			// An archived service keeps its name: say so, as it isn't in
			// the list the caller sees.
			if held, gerr := q.GetServiceByName(ctx, store.GetServiceByNameParams{EnvironmentID: es.env.ID, Name: name}); gerr == nil && held.ArchivedAt != nil {
				if opts.marksFrom != 0 {
					return conflict("service %q in %s is archived and still holds that name; restore under another name with `--as <name>`", name, es)
				}
				return conflict("service %q in %s is archived and still holds that name; pick another name", name, es)
			}
			return conflict("service %q already exists in %s", name, es)
		}
		if err != nil {
			return err
		}
		if err := q.SetServiceTemplate(ctx, store.SetServiceTemplateParams{Template: string(t.name), ID: s.ID}); err != nil {
			return err
		}
		s.Template = string(t.name)
		if t.database != "" {
			if s, err = q.SetServiceDatabaseSettings(ctx, store.SetServiceDatabaseSettingsParams{Database: string(t.database), ID: s.ID}); err != nil {
				return err
			}
		}
		ss = svcScope{es, s}
		if _, err := q.CreateVolume(ctx, store.CreateVolumeParams{
			ServiceID: s.ID, Name: templateVolume, MountPath: t.mountPath, Pending: true, DockerName: volumeName(ss, templateVolume),
		}); err != nil {
			return err
		}
		if opts.marksFrom != 0 {
			copied := store.CopySensitiveMarksParams{ToService: s.ID, FromService: opts.marksFrom}
			if err := q.CopySensitiveMarks(ctx, copied); err != nil {
				return err
			}
			if err := q.CopySensitiveKeys(ctx, store.CopySensitiveKeysParams(copied)); err != nil {
				return err
			}
		}
		vars := t.vars(name, newPassword())
		maps.Copy(vars, opts.keep)
		for _, k := range slices.Sorted(maps.Keys(vars)) {
			if err := c.stageSet(ctx, q, es.env.ID, &s.ID, k, vars[k]); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		return ss, err
	}
	c.audit(ctx, a, "service.create", &es.project, &es.env, ss.String(),
		fmt.Sprintf("created service from the %s template (%s), with a volume and generated credentials", t.name, image))
	if opts.noDeploy {
		return ss, nil
	}
	return ss, c.deployTemplate(ctx, a, ss, opts.done)
}

// deployTemplate starts the first release of a template service.
func (c *Core) deployTemplate(ctx context.Context, a Actor, ss svcScope, done func(ok bool)) error {
	rel, err := c.startRelease(ctx, a, ss, releaseSpec{source: apitypes.SourceImage, done: done})
	if err != nil {
		return errf(CodeOf(err), "created %s, but couldn't deploy it: %v. Deploy it once that's fixed: dock deploy -s %s", ss.svc.Name, err, ss.svc.Name)
	}
	c.audit(ctx, a, "release.deploy", &ss.project, &ss.env, ss.String(), fmt.Sprintf("release %d from image %s", rel.Number, rel.ImageRef))
	return nil
}

// afterActive runs a template's follow-up once one of its releases went
// active: Dock sets up data access for a template database (Postgres,
// Redis) that has none yet (ADR 0016: automatic for templates, since Dock
// owns the credentials), and for Postgres creates the query stats
// extension when the start command loads it and it doesn't exist yet
// (ADR 0069): one owner connection per activation, nothing when it
// exists.
//
// ctx is the deploy's, which ends when the deploy returns (deployRuns),
// so only the first attempt runs under it: the retries have the daemon's
// context. Under the deploy's they never ran, and a database that missed
// its first attempt stayed without data access.
func (c *Core) afterActive(ctx context.Context, ss svcScope) {
	t, ok := templateOf(ss.svc)
	if !ok || t.database == "" {
		return
	}
	_, err := c.store.GetDataAccess(ctx, ss.svc.ID)
	needSetup := store.IsNotFound(err)
	if err != nil && !needSetup {
		return // unknown: leave it to an admin
	}
	wantStats := t.database == apitypes.DatabasePostgres && loadsQueryStats(ss.svc.StartCommand)
	if !needSetup && !wantStats {
		return
	}
	ref := ServiceRef{ss.project.Name, ss.env.Name, ss.svc.Name}
	sys := System.InOrg(ss.project.OrgID)
	setup := func(ctx context.Context) error {
		if needSetup {
			if err := c.ensureDataAccess(ctx, ss); err != nil {
				return err
			}
			needSetup = false
		}
		if wantStats {
			_, err := c.EnableDataQueryStats(ctx, sys, ref)
			return err
		}
		return nil
	}
	if setup(ctx) == nil || ctx.Err() != nil {
		return
	}
	// The retries run in the background: the deploy is done.
	c.goCounted("setting up a template database", func() {
		ctx := c.ctx
		delay := setupRetryDelay
		for attempt := 2; ; attempt++ {
			select {
			case <-time.After(delay):
			case <-ctx.Done():
				return
			}
			err := setup(ctx)
			if err == nil || ctx.Err() != nil {
				return
			}
			if attempt == setupAttempts {
				c.log.Warn("set up data access or query stats for template database", "service", ss.String(), "err", err)
				return
			}
			delay *= 2
		}
	})
}

// ensureDataAccess sets up data access for a template database that has
// none yet. afterActive's tries and a restore that just filled the
// database (restore.finish) both call it: the restore so that it isn't
// reported done while a try that came too early still waits for its
// retry. A setup rotates the role passwords, so setupMu keeps two of them
// from crossing.
func (c *Core) ensureDataAccess(ctx context.Context, ss svcScope) error {
	c.setupMu.Lock()
	defer c.setupMu.Unlock()
	if _, err := c.store.GetDataAccess(ctx, ss.svc.ID); !store.IsNotFound(err) {
		return err
	}
	_, err := c.SetupData(ctx, System.InOrg(ss.project.OrgID), ServiceRef{ss.project.Name, ss.env.Name, ss.svc.Name})
	return err
}

// Setting up a new template database is retried. A Postgres template's
// health check passes only once the server accepts connections
// (node.HealthPostgres), but a server on an older dock still runs the
// TCP check, which passes a moment before Postgres accepts logins, and
// the other engines' checks are TCP too; the image's entrypoint also
// restarts Postgres once after initialising a new volume. The waits (1,
// 2, 4 and 8 s) run only after a failed attempt, never while idle.
const setupAttempts = 5

// setupRetryDelay is the wait before the second attempt; tests shorten it.
var setupRetryDelay = time.Second

// templateNames lists the database templates' names for an error.
func templateNames() string {
	names := make([]string, 0, len(templates))
	for name := range templates {
		names = append(names, string(name))
	}
	slices.Sort(names)
	return strings.Join(names, ", ")
}
