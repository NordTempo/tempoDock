// dbTemplate is a database template (ADR 0019): a regular service with a
// pinned image, a volume, generated credentials and small-server defaults.
// After creation it is an ordinary service; the template only drives health
// checks, backups, restores and data setup.
type dbTemplate struct {
	name        apitypes.Template
	title       string
	description string
	// license is the database's, as the template catalog shows it.
	license string
	image   string
	// port is where the database listens. It isn't published: health
	// checks probe it on the environment network, as backups reach it.
	port int
	// health is what the health checks ask the port beyond a TCP connect
	// (node.HealthPostgres for Postgres, "" for the others).
	health    node.HealthKind
	mountPath string
	memoryMB  int
	// cmd keeps the image's entrypoint (it initialises the volume) and
	// adds the tuning.
	cmd string
	// database is the data panel setting it sets ("" for none yet).
	database apitypes.DatabaseSetting
	backup   apitypes.BackupKind
	// vars are the service's variables, given its name; passwords are
	// generated by the caller (newPassword).
	vars    func(service, password string) map[string]string
	exports []string
}

// volumeName of every template's volume.
const templateVolume = "data"

