/** The flag of an ISO country code, as an emoji: "NO" is 🇳🇴. */
export const flag = (code: string) =>
  /^[A-Z]{2}$/.test(code)
    ? String.fromCodePoint(...[...code].map((c) => 0x1f1a5 + c.charCodeAt(0)))
    : "";

/** Dimensions whose values get a glyph. */
const glyphed = new Set(["browser", "os", "device"]);

/**
 * A breakdown value with its flag or glyph in front, or the text alone
 * for dimensions that have none.
 */
export function Labeled({
  dimension,
  value,
  children,
}: {
  dimension: string;
  value: string;
  children: ReactNode;
}) {
  const icon =
    dimension === "country" ? (
      flag(value) && (
        <span aria-hidden className="w-4 flex-none text-center leading-none">
          {flag(value)}
        </span>
      )
    ) : glyphed.has(dimension) && value ? (
      <svg
        viewBox="0 0 24 24"
        aria-hidden
        className="size-3.5 flex-none fill-mut"
      >
        <path d={paths[value] ?? globe} />
      </svg>
    ) : null;
  if (!icon) return <>{children}</>;
  return (
    <span className="inline-flex max-w-full min-w-0 items-center gap-1.5 align-bottom">
      {icon}
      <span className="min-w-0 truncate">{children}</span>
    </span>
  );
}
